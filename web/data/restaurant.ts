/* ─────────────────────────────────────────────
   Menu types
───────────────────────────────────────────── */
export type MenuItemOption = { name: string; priceMod: number }

export type SideConfig = {
  options: MenuItemOption[]
  max: number
}

export type MenuItem = {
  id: string
  name: string
  description: string
  basePrice: number
  image: string
  category: string
  // Customization
  sizeOptions?: MenuItemOption[]
  proteinOptions?: MenuItemOption[]
  sides?: SideConfig
  modifiers?: string[]        // toggle pills — restaurants pick a max of 8 per dish
  allowsNotes: boolean
  isQuickAdd: boolean         // true → no sheet, goes straight to cart
  // Dietary
  dietaryTags?: ("vegetarian" | "vegan" | "halal")[]
  allergens?: string[]
  bundleSuggestionIds?: string[]
}

export type RestaurantMenu = {
  categories: string[]
  items: MenuItem[]
}

export type RestaurantWithMenu = Restaurant & { menu: RestaurantMenu }

